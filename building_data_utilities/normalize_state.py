def normalize_state(state_name: str) -> str:
    """
    Normalize a state name (or abbreviation) to its standard two-letter abbreviation.

    Args:
        state_name: Full state name or abbreviation

    Returns:
        Standardized state abbreviation. If the input isn't a recognized full state name
        and isn't already a two-letter abbreviation, the uppercased input is returned as-is.
    """
    if not state_name:
        return ""

    state_lower = state_name.lower().strip()

    # If it's already an abbreviation, return uppercase
    if len(state_lower) == 2 and state_lower.isalpha():
        return state_lower.upper()

    # Look up full name
    return STATE_ABBREVIATIONS.get(state_lower, state_name.upper())
